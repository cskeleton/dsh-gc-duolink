import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({
  executablePath: process.env.BROWSER_EXECUTABLE_PATH ?? '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser',
  headless: true,
})
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = [], network = []
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()) })
const click = selector => page.locator(selector).click()
const text = selector => page.locator(selector).textContent()
const hidden = selector => page.locator(selector).evaluate(el => el.classList.contains('hidden'))
let checks = 0
function check(value, message) { assert.ok(value, message); checks++; console.log(`PASS ${message}`) }
try {
  await page.goto(new URL('./session-link.html', import.meta.url).href)
  check(await text('#count') === '1', 'Initial linked count')
  check(await page.locator('.session-row > .dot').count() === 4, 'Host status position is preserved on every row')
  const rowLink = page.locator('[data-row-link="b"]')
  check(await rowLink.evaluate(el => getComputedStyle(el).opacity) === '0', 'Right link action hidden without hover or focus')
  await page.locator('[data-session="b"]').hover()
  check(await rowLink.evaluate(el => getComputedStyle(el).opacity) === '1', 'Right link action shown on row hover')
  const titleBox = await page.locator('[data-session="b"]').boundingBox()
  const linkBox = await rowLink.boundingBox()
  check(linkBox.x > titleBox.x + titleBox.width, 'Link action is to the right of session title')
  await rowLink.click()
  check((await text('.owner-note')).includes('auto-wake 测试 · 非当前对话'), 'Hover action manages its row rather than current conversation')
  check(await text('#current-title') === '互联测试 1', 'Hover action preserves current conversation')
  await click('#close-panel')
  await page.locator('#current-title').hover()
  await rowLink.focus()
  check(await rowLink.evaluate(el => getComputedStyle(el).opacity) === '1', 'Keyboard focus also reveals right link action')
  await page.locator('#quick-open').focus()
  await click('#send-ba')
  check((await text('#status-a')).includes('1 条待处理'), 'Reply queues without creator wake grant')
  await click('#manual')
  check(!(await text('#status-a')).includes('待处理'), 'Manual start drains queued reply')
  await click('#send-ab')
  check((await text('#log')).includes('A → B：模拟自动唤醒'), 'Forward auto wake works in simulator')
  await click('#directions')
  check(await page.locator('[data-wake="ab"][data-target="a"]').getAttribute('aria-checked') === 'false', 'Creator wake initially off')
  await click('[data-wake="ab"][data-target="a"]')
  await click('#send-ba')
  check((await text('#log')).includes('B → A：模拟自动唤醒'), 'Enabling creator wake permits automatic reply processing')
  check(await text('#count') === '1', 'Wake toggle does not change link membership')
  await page.screenshot({ path: new URL('./management-preview.png', import.meta.url).pathname, fullPage: true })
  await click('#close-panel')
  await click('#quick-open')
  check(await page.locator('#create-link').isDisabled(), 'No grant before explicit peer selection')
  check(await page.locator('[data-pick="a"],[data-pick="b"]').count() === 0, 'Self and linked peers excluded')
  await page.locator('#search').fill('missing')
  check((await text('#candidates')).includes('没有匹配'), 'No-match search state')
  await page.locator('#search').fill('session-demo-c')
  await click('[data-pick="c"]')
  check(await text('#count') === '1', 'Selecting candidate alone never creates link')
  await page.keyboard.press('Escape')
  check(await hidden('#picker'), 'Escape dismisses quick link')
  check(await page.locator('#quick-open').evaluate(el => el === document.activeElement), 'Escape returns focus')
  await click('#quick-open')
  await click('[data-pick="c"]')
  await page.screenshot({ path: new URL('./quick-link-preview.png', import.meta.url).pathname, fullPage: true })
  await page.locator('#wake-peer').uncheck()
  await page.locator('#wake-self').uncheck()
  await click('#create-link')
  check(await text('#count') === '2', 'Explicit confirmation creates link even with both wakes off')
  check(await page.locator('.session-row:has([data-session="c"]) > .dot.running').count() === 1, 'Running status remains after linking')
  check(await page.locator('[data-row-link="c"]').evaluate(el => el.classList.contains('is-linked')), 'Running linked session has independent right-side link action')
  check((await page.locator('[data-row-link="a"]').getAttribute('title')).includes('2 个会话'), 'Link count updates independently of auto wake')
  await click('[data-menu="c"]')
  await click('#menu-link')
  check((await text('.owner-note')).includes('互联测试 2 · 非当前对话'), 'Row menu manages clicked session without switching conversation')
  check(await text('#current-title') === '互联测试 1', 'Main conversation preserved')
  check(await page.locator('#panel [role=switch][aria-checked=false]').count() === 2, 'Both selected wake values persisted')
  await click('[data-unlink="a-c"]')
  await click('#cancel-unlink')
  check(await text('#count') === '2', 'Unlink cancellation preserves group')
  await click('[data-unlink="a-c"]')
  await click('[data-confirm="a-c"]')
  check(await text('#count') === '1', 'Confirmed unlink updates count')
  await click('#reset')
  await page.setViewportSize({ width: 390, height: 844 })
  await click('#quick-open')
  const bounds = await page.locator('#picker').boundingBox()
  check(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0 && bounds.y + bounds.height <= 844, 'Mobile picker fits viewport')
  await click('[data-pick="d"]')
  await click('#create-link')
  check(await text('#count') === '2', 'Mobile link creation works')
  await click('#directions')
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout has no horizontal overflow')
  await page.screenshot({ path: new URL('./mobile-preview.png', import.meta.url).pathname, fullPage: true })
  await click('#reset')
  check(await text('#count') === '1', 'Reset restores initial state')
  check(errors.length === 0, `No browser errors: ${errors.join('; ')}`)
  check(network.length === 0, 'No HTTP requests or real host mutations')
  console.log(`\n${checks} checks passed.`)
} finally {
  await browser.close()
}
